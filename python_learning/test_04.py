"""
test_04.py — pytest 框架：一个命令跑所有用例，自动汇总结果
============================================================

Postman 对照：
    Collection Runner → 选集合 → 点 Run → 显示几个 Pass 几个 Fail
    pytest 命令       → 输 pytest 文件名 → 自动找到 test_ 开头的函数 → 逐个执行 → 汇总

两个核心规则（pytest 就这么简单）：
    规则1：函数名必须以 test_ 开头（pytest 靠名字识别哪些是测试用例）
    规则2：用 assert 做判断（跟 test_03 一模一样）

==============================================================================
看懂 pytest 的输出：
==============================================================================

    collected 2 items                          ← 找到了 2 个测试用例

    test_04.py::test_状态码正确 PASSED   [ 50%] ← 第1个过了，进度 50%
    test_04.py::test_返回数据正确 PASSED [100%] ← 第2个过了，进度 100%

    2 passed in 2.73s                          ← 汇总：2 个全过

    如果某个挂了会显示：
    test_04.py::xxx FAILED               [100%] ← 红色 FAILED
    1 passed, 1 failed                          ← 汇总：1过1挂

==============================================================================
关键理解：
==============================================================================

    以前：python test_03.py  → 一个文件里所有代码从上到下跑一遍
    现在：pytest test_04.py  → 只跑 test_ 开头的函数，每个函数是一个独立用例

    为什么这样更好？
    - 用例1挂了，用例2照跑（不会因为前面报错后面就不跑了）
    - 自动统计：几个过几个挂，不用自己数
    - 一条命令跑整个文件夹：pytest python_learning/ -v
      （项目中几十上百个用例，一个命令全部跑完）
"""

import requests

# ============================================================
# 测试用例1：验证状态码
# ============================================================
# def = define（定义一个函数）
# test_ 开头 = 告诉 pytest "这是测试用例，请执行它"
# 函数名用中文 = 报告里直接显示中文，一眼就知道测的什么
def test_状态码正确():
    """验证接口返回 200"""
    r = requests.get("https://postman-echo.com/get?name=你的名字")
    assert r.status_code == 200


# ============================================================
# 测试用例2：验证返回数据正确
# ============================================================
def test_返回数据正确():
    """验证服务器回显的 name 字段正确"""
    r = requests.get("https://postman-echo.com/get?name=你的名字")
    data = r.json()                              # 先把整个 JSON 存到变量 data 里
    assert data["args"]["name"] == "你的名字"     # 然后直接用 data["..."]["..."] 取值
    #  ↑
    #  写成 data = r.json() 的好处：只调一次 .json()
    #  如果要写多个断言，不用每次都 r.json()["..."]，直接 data["..."] 就行

# ============================================================
# pytest 常用命令速查：
# ============================================================
#   pytest python_learning/test_04.py -v    ← 跑单个文件，-v 显示每个用例名
#   pytest python_learning/ -v              ← 跑整个文件夹所有 test_ 文件
#   pytest python_learning/ -v -q           ← -q 简洁模式，只显示点和结果
#   pytest python_learning/ --tb=short      ← 报错时缩短堆栈信息，更容易看
