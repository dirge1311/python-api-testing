"""
test_02.py — Python 发 POST 请求（= Postman 的 Body → raw → JSON）
===================================================================

GET 和 POST 的核心区别：
    ┌──────────┬──────────────────────┬──────────────────────┐
    │          │        GET           │        POST          │
    ├──────────┼──────────────────────┼──────────────────────┤
    │ 用途     │ 查数据（查商品/查用户）│ 提交数据（登录/下单）  │
    │ 数据位置 │ URL 问号后面          │ json={} 参数里       │
    │ Postman  │ Params 标签页         │ Body → raw → JSON   │
    │ 函数     │ requests.get()        │ requests.post()     │
    └──────────┴──────────────────────┴──────────────────────┘
"""

import requests

# ============================================================
# 第1步：准备要发送的数据（= Postman Body 里写的 JSON）
# ============================================================
# Python 字典格式，跟 JSON 一模一样，区别只是：
#   JSON 写       "username": "admin"
#   Python 字典也写 "username": "admin"  （写法完全一样，所以很好记）
data = {
    "username": "Qiucen_Lyu",
    "password": "123"
}

# ============================================================
# 第2步：发 POST 请求
# ============================================================
# requests.post(url, json=数据) 做了三件事：
#   ① 把 data 字典自动转成 JSON 字符串（你不用管，自动的）
#   ② 自动加上 Content-Type: application/json 请求头（也不用管）
#   ③ 发出去，返回服务器的响应
r = requests.post("https://postman-echo.com/post", json=data)
#                                                  ↑
#                                     json=  表示"我的数据是 JSON 格式"
#                                     写这个就行，不用像 Postman 一样手动选 raw→JSON

# ============================================================
# 第3步：看返回结果
# ============================================================
print(r.json())

# ============================================================
# 输出结果解读：
# ============================================================
# {
#   'args': {},                           ← GET 的参数（POST 没有，所以是空的）
#   'data': {'username': '...', ...},     ← 你发的原始数据，服务器收到了
#   'json': {'username': '...', ...},     ← 服务器识别出这是 JSON 格式
#   'url': 'https://postman-echo.com/post'← 请求地址
#   'headers': {                          ← 服务器收到的请求头
#       'content-type': 'application/json'← 自动加上的，说明是 JSON 数据
#   }
# }
#
# 重点看两个字段：
#   'data' → 确认数据原样发出去了
#   'json' → 确认服务器正确识别成了 JSON
#   两个都有你的 username 和 password，说明请求成功

# ============================================================
# GET vs POST 速记：
# ============================================================
# GET  = 你去图书馆查书           → 只是看，不改变任何东西
# POST = 你去前台登记借书          → 提交了数据，服务器那边产生了变化
#
# 所以：
#   商品查询、用户查询 → GET（只是看看）
#   登录、下单、注册   → POST（提交了东西过去）
