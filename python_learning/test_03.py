"""
test_03.py — 断言（assert）：判断接口返回结果对不对
======================================================

核心概念：
    Postman Tests 标签页写的 pm.expect() → Python 里就是 assert
    assert = "我断言"
    后面跟一个判断题（True/False）
    True  → 没反应，继续往下跑
    False → 红色报错 AssertionError，停在那一行

一句话记住：
    assert 实际值 == 预期值
    "我断言  这个   等于  那个"
"""

import requests

# ============================================================
# 发请求（跟 test_01 一样）
# ============================================================
r = requests.get("https://postman-echo.com/get?name=Qiucen_Lyu")

# ============================================================
# 断言1：状态码 == 200
# ============================================================
# Postman 写法：
#   pm.test("状态码为200", function () {
#       pm.response.to.have.status(200);
#   });
#
# Python 写法：
assert r.status_code == 200
#      └──────────┘   └─┘
#      实际值（服务器返回的状态码）
#                     预期值（你期望它是多少）
#
# 读法："我断言，状态码等于 200"
# 跑完没报错 = 断言通过，状态码确实是 200

# ============================================================
# 断言2：返回的某个字段值等于预期值
# ============================================================
# Postman 写法：
#   var res = pm.response.json();
#   pm.expect(res.args.name).to.eql("Qiucen_Lyu");
#
# Python 写法：
assert r.json()["args"]["name"] == "Qiucen_Lyu"
#      └───────────────────┘     └──────────┘
#      实际值：一层一层取到 name    预期值
#
# r.json() 返回的 JSON 结构长这样：
#   {
#     "args": {              ← 第一层 key
#       "name": "Qiucen_Lyu" ← 第二层 key
#     }
#   }
# 所以取 name 的路径是：r.json()["args"]["name"]
# 跟 Postman 里点开 JSON 一层层展开找字段，完全一样
#
# 取值的语法：字典["key名"]
# 套娃取值：  字典["外层key"]["内层key"]

# ============================================================
# 断言3：某个字段是否存在
# ============================================================
# Postman 写法：
#   pm.expect(res.json()).to.have.property("args");
#
# Python 写法：
assert "args" in r.json()
#      └──┘    └───────┘
#      字段名   在...里面吗？
#
# in 关键字 = "在...里面吗"
# 可以用在任何需要检查"有没有"的场景：
#   "args" in r.json()              → args 字段在 JSON 里吗？
#   "phone" in ["phone", "laptop"]  → phone 在列表里吗？
#   "error" not in response_text    → error 不在返回值里吗？

print("全部断言通过！")

# ============================================================
# 断言速查卡片（面试和日常都只用这四种）：
# ============================================================
#
#   assert r.status_code == 200                  ← 状态码
#   assert r.json()["key"] == 预期值             ← 字段值相等
#   assert "key" in r.json()                     ← 字段存在
#   assert 值 in 列表                             ← 包含判断
#
# ============================================================
# 新手坑：
# ============================================================
# ❌ assert r.json()["name"] ...  字段名写错 → KeyError（检查大小写和拼写）
# ❌ assert r.status_code == "200" 数字写成字符串 → 200 != "200" 断言失败
# ❌ assert r.json["args"]         .json 漏了括号 → 不是函数调用
# ✅ assert r.json()["args"]       正确写法
