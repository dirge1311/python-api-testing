"""
test_01.py — Python 发 GET 请求（接口测试的第一步）
====================================================

对照 Postman 理解：
    你在 Postman 里的操作            →  Python 里的代码
    ─────────────────────            ─────────────────
    ① 下拉选 GET                     →  requests.get()
    ② URL 输入框填地址                →  括号里的 URL 字符串
    ③ 点 Send 按钮                   →  这行代码一执行就等于点了 Send
    ④ 右上角看状态码（200/400...）    →  r.status_code
    ⑤ 下面 Body 看返回的 JSON        →  r.json()

公司项目里最常用的三种请求写法：
    requests.get(url)             → 查数据（查商品、查用户）
    requests.post(url, json={})   → 提交数据（登录、下单）
    requests.put(url, json={})    → 更新数据（改密码、改收货地址）
"""

# ============================================================
# 第1步：导入 requests 库
# ============================================================
# 作用：把"发 HTTP 请求"的能力加载进来
# 类比：就像 Postman 这个软件本身 —— 没有它你发不了请求
# 学一个库就要 import 一个，后面还会学 import pytest
import requests

# ============================================================
# 第2步：发 GET 请求（基础版，无参数）
# ============================================================
# requests.get() = Postman 里「选 GET + 填 URL + 点 Send」三合一
# r = Response 的缩写，服务器返回的整个响应包都存在 r 里
r = requests.get("https://postman-echo.com/get?name=zhangsan")

# ============================================================
# 第3步：看状态码
# ============================================================
# .status_code = 只看 HTTP 状态码
# 200 = 成功    400 = 客户端请求有问题    500 = 服务器炸了
# 等价于 Postman Response 面板右上角那个数字
print(r.status_code)   # 输出 200 表示请求成功

# ============================================================
# 练习1：改参数 —— 把 name=zhangsan 换成你自己的名字
# ============================================================
# URL 里 ? 后面的部分叫"查询参数"（Query Params）
# 格式：?参数名1=值1&参数名2=值2
# 这在 Postman 里就是 Params 标签页填的 Key-Value
r = requests.get("https://postman-echo.com/get?name=Qiucen_Lyu")
#                                             ↑
#                                      ? 开头表示"后面是参数了"
#                                      name=Qiucen_Lyu 就是你传的参数

# ============================================================
# 练习2：加多个参数 —— 用 & 连接
# ============================================================
# 多个参数用 & 符号拼接：?参数1=值1&参数2=值2
# Postman 里 Params 标签页你填多行 Key-Value 就是这个效果
r = requests.get("https://postman-echo.com/get?name=Qiucen_Lyu&age=22")
#                                             ↑                    ↑
#                                     第一个参数 name         & 连接第二个参数 age

# ============================================================
# 练习3：看完整返回内容 —— 用 .json()
# ============================================================
# r.json() = 把服务器返回的 JSON 解析成 Python 字典
# 等价于 Postman 里 Response Body 面板选 Pretty 格式
# 注意：只有最后一次请求的响应会被打印
#      上面那行 r = requests.get(...) 的结果已经把之前的结果覆盖了
print(r.json())

# ============================================================
# 输出结果解读：
# ============================================================
# {
#   'args':    {'name': 'Qiucen_Lyu', 'age': '22'},  ← 服务器收到了你的参数！
#   'headers': {...},                                  ← 请求头（不重要，略过）
#   'url':     '...?name=Qiucen_Lyu&age=22'           ← 完整的请求地址
# }
#
# 重点看 'args' 这个字段 —— postman-echo 会把收到的参数原样返回
# 你传了 name 和 age，它就回 name 和 age
# 这是验证"参数确实发出去了"的最直接方式

# ============================================================
# 容易犯的错：
# ============================================================
# ❌ 写错：requests.get(  →  漏了 import requests 会报 NameError
# ❌ 写错：print(r.json)  →  漏了括号 ()，不会报错但打印的是函数地址不是内容
# ✅ 正确：print(r.json()) →  必须加括号才是调用函数
# ❌ 写错：新请求用同一个变量名 r → 会覆盖上一次的结果（上面练习就演示了这个现象）
#         想保留多次请求结果的话，用不同变量名：r1 = ... / r2 = ...
