# ============================================================
# 第1个：pwd — 我在哪
# ============================================================
# pwd = Print Working Directory（打印当前目录）
# 像 VS Code 顶部的路径栏，告诉你当前在哪个文件夹
#
#   $ pwd
#   /d/code/claude-test


# ============================================================
# 第2个：ls — 这下面有什么
# ============================================================
# ls = List（列出文件和文件夹）
#
#   $ ls           列出文件名
#   $ ls -l        详细列表（大小、日期、权限）
#   $ ls -a        显示隐藏文件（.开头的那种）
#   $ ls -la       两个合起来 = 最常用写法（详细 + 隐藏）


# ============================================================
# 第3个：cd — 去别的地方
# ============================================================
# cd = Change Directory（切换目录）
#
#   $ cd python_learning/          进入子文件夹
#   $ cd ..                        返回上一级
#   $ cd /d/code/claude-test       直接跳过去（绝对路径）


# ============================================================
# 第4个：cat — 看看文件内容
# ============================================================
# cat = Concatenate（显示文件内容）
#
#   $ cat test_01.py               把文件内容打印到屏幕
#   $ cat app.log | head -50       只看前 50 行（大文件很有用）


# ============================================================
# 第5个：grep — 搜东西
# ============================================================
# grep = Global Regular Expression Print（搜索文本）
# 测试看日志的核心命令
#
#   $ grep "ERROR" app.log             找出所有含 ERROR 的行
#   $ grep -i "error" app.log          -i = 忽略大小写
#   $ grep "2024-07-27" app.log | grep "ERROR"   搜特定日期的错误
#   $ grep -c "ERROR" app.log          统计有几行 ERROR


# ============================================================
# 第6个：tail — 看最新日志
# ============================================================
# tail = 看文件末尾（日志永远追加在末尾，所以看日志用它）
#
#   $ tail app.log                    看最后 10 行
#   $ tail -n 100 app.log             看最后 100 行
#   $ tail -f app.log                 -f = follow，实时刷新
#                                     新的日志一行行自己往外跳，像电影字幕
#                                     这是测试看日志最常用的命令


# ============================================================
# 第7个：head — 看文件开头
# ============================================================
#   $ head app.log                    看前 10 行
#   $ head -n 50 app.log              看前 50 行


# ============================================================
# 第8个：ps — 看进程
# ============================================================
# ps = Process Status（进程状态）
#
#   $ ps aux | grep python            看 Python 进程在不在跑
#   $ ps aux | grep nginx             看 Web 服务器在不在


# ============================================================
# 第9个：cp / mv / rm — 复制 / 移动 / 删除
# ============================================================
#   $ cp 源文件 目标文件              复制（Copy）
#   $ mv 源文件 目标位置              移动/重命名（Move）
#   $ rm 文件名                       删除（Remove，删了就没了，谨慎）


# ============================================================
# 第10个：管道符 | — 把左边的结果传给右边
# ============================================================
# | = 管道，不是字母 L 也不是感叹号
# 键盘上 Enter 键上方那个键，Shift + \
#
#   $ cat app.log | grep "ERROR"      看日志 → 过滤错误
#   $ cat app.log | grep "ERROR" | wc -l  看日志 → 过滤错误 → 数几行
#   $ ps aux | grep python            看进程 → 过滤 python 相关的

# ============================================================
# 一张图记住所有命令
# ============================================================
#
#   pwd           我在哪
#   ls -la        这有什么
#   cd xxx        去哪
#   cat 文件      看文件
#   grep 关键词   搜东西
#   tail -f 文件  看实时日志（测试最常用）
#   ps aux        看进程
#   cp / mv / rm  复制 移动 删除
#   | 管道        左边传给右边
#   > 重定向      输出写进文件（比如 grep ERROR > bug.txt）

